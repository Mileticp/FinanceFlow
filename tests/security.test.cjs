const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p));
const html=read('index.html').toString();
const release=JSON.parse(read('shell-release.json').toString());
test('CSP enforces only hashed inline application script',()=>{
 const meta=html.match(/<meta name="financeflow-csp" http-equiv="Content-Security-Policy" content="([^"]+)">/);
 assert.ok(meta,'CSP meta tag must exist');
 const policy=meta[1];
 const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
 assert.equal(scripts.length,1,'all other scripts must be external');
 const hash=crypto.createHash('sha256').update(scripts[0][1]).digest('base64');
 assert.ok(policy.includes("'sha256-"+hash+"'"),'inline script hash must match compiled HTML');
 assert.match(policy,/script-src 'self' 'sha256-/);
 assert.doesNotMatch(policy,/script-src [^;]*'unsafe-inline'/);
 assert.doesNotMatch(policy,/script-src [^;]*'unsafe-eval'/);
 assert.match(policy,/object-src 'none'/);
 assert.match(policy,/base-uri 'self'/);
 assert.doesNotMatch(html,/<script[^>]+src="https?:\/\//,'scripts should be served from versioned local assets');
});
test('pinned Supabase 2.118.0 is vendored in immutable cache with SRI',()=>{
 const vendor=read('vendor/supabase.min.js');
 assert.ok(vendor.length>10000);
 const digest=crypto.createHash('sha256').update(vendor).digest('hex');
 const asset='./shell/supabase.min.'+digest.slice(0,16)+'.js';
 const info=release.assets.find(x=>x.url===asset);
 assert.ok(info,'Supabase must appear in service worker release cache');
 assert.equal(info.sha256,digest);
 assert.deepEqual(read(asset),vendor);
 const b64=crypto.createHash('sha256').update(vendor).digest('base64');
 assert.ok(html.includes('data-shell-source="vendor/supabase.min.js"'));
 assert.ok(html.includes('integrity="sha256-'+b64+'"'));
 assert.doesNotMatch(html,/@supabase\/supabase-js@2(?:\/|")/);
});
test('render escape helper handles HTML and attribute injection',()=>{
 const source=read('js/app.js').toString();
 const match=source.match(/const E=value=>([^;\n]+);/);
 assert.ok(match);
 const vm=require('node:vm');
 const encode=vm.runInNewContext('value=>'+match[1]);
 const payload='" onerror="globalThis.injected=true" <img src=x onerror=alert(1)> &';
 const escaped=encode(payload);
 assert.ok(escaped.includes('&quot;'));
 assert.ok(escaped.includes('&lt;img'));
 assert.ok(escaped.includes('&amp;'));
 assert.ok(!escaped.includes('<img'));
 assert.ok(!escaped.includes('" onerror='));
});
